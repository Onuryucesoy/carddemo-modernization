#!/usr/bin/env bash
# Presenter helper for the live demo. Usage: modern/demo.sh <step>
#   check   tool versions
#   golden  re-run the unmodified COBOL and regenerate the golden master
#   test    run the Java parity + business-rule tests
#   bug     show legacy defect LD-1 (last account never updated)
#   break   change truncation to rounding and show the tests fail
#   fix     revert the change and show the tests pass again
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SVC="$ROOT/modern/interest-service"
CALC="$SVC/src/main/java/com/carddemo/interest/InterestCalculator.java"
GM="$ROOT/modern/golden-master"

mvn_test() {
  local out rc=0
  out="$(cd "$SVC" && mvn -B test 2>&1)" || rc=$?
  echo "$out" | grep -E "^\[ERROR\]   |Tests run: [0-9]+, Failures: [0-9]+, Errors: [0-9]+, Skipped: [0-9]+$" | sed -e "s/^\[[A-Z]*\] *//" -e "s/account master after REWRITE ==>.*/Java account file no longer matches legacy COBOL output/" | cut -c1-110
  [ "$rc" -eq 0 ] && echo "RESULT: ALL TESTS PASS" || echo "RESULT: TESTS FAILED"
}

case "${1:-}" in
  check)
    v="$(cobc --version)"; echo "${v%%$'\n'*}"
    v="$(java -version 2>&1)"; echo "${v%%$'\n'*}"
    v="$(mvn -v 2>&1)"; echo "${v%%$'\n'*}" ;;
  golden)
    "$GM/run-cobol.sh" seed
    "$GM/run-cobol.sh" month-end
    echo; echo "--- legacy program output (month-end) ---"; cat "$GM/expected/month-end/sysout.txt" ;;
  test)
    (cd "$SVC" && mvn -B test 2>&1 | grep -E "Tests run:|BUILD") ;;
  bug)
    echo "Current balance per account (COBOL zoned decimal, last char = sign + last digit):"
    printf "  %-12s %-14s %-14s\n" ACCOUNT BEFORE AFTER
    cut -c46-56 "$GM/expected/month-end/transact.txt" | sort -u > /tmp/demo-txn-accts
    paste -d' ' <(cut -c1-11,13-24 "$GM/fixtures/month-end/acctdata.txt") \
                <(cut -c13-24 "$GM/expected/month-end/acctdata.txt") \
      | while read -r line; do
          acct="${line:0:11}"; before="${line:11:12}"; after="${line:24:12}"; note=""
          if grep -qx "$acct" /tmp/demo-txn-accts; then
            [ "$before" = "$after" ] && note="<-- interest transaction written, balance NOT posted (LD-1)"
          else
            note="(zero-rate group: no interest, as designed)"
          fi
          printf "  %-12s %-14s %-14s %s\n" "$acct" "$before" "$after" "$note"
        done
    echo; echo "Interest transactions generated by the legacy program:"
    cut -c1-16,23-56 "$GM/expected/month-end/transact.txt" | sed 's/^/  /' ;;
  break)
    sed -i 's/MONTHS_TIMES_PERCENT, 2, RoundingMode.DOWN)/MONTHS_TIMES_PERCENT, 2, RoundingMode.HALF_UP)/' "$CALC"
    grep -n "RoundingMode.HALF_UP" "$CALC"
    mvn_test ;;
  fix)
    sed -i 's/MONTHS_TIMES_PERCENT, 2, RoundingMode.HALF_UP)/MONTHS_TIMES_PERCENT, 2, RoundingMode.DOWN)/' "$CALC"
    grep -n "MONTHS_TIMES_PERCENT, 2, RoundingMode" "$CALC"
    mvn_test ;;
  *) sed -n '2,9p' "$0"; exit 1 ;;
esac
